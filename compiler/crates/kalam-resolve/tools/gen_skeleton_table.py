"""Generates the vendored identifier-skeleton table of kalam-resolve (spec 5.3, DR-04).

    skeleton(id) = UTS39_skeleton( arabic_fold( NFKC(id) ) )

Identifiers reach the resolver in NFC (SEC0101), so the skeleton is computed one code point
at a time: for each code point `c` that can occur in an identifier (XID_Continue, which
includes every XID_Start character),

    piece(c) = NFD( prototypes( NFD( arabic_fold( NFKC(c) ) ) ) )

and skeleton(id) is the concatenation of piece(c) over the identifier. The table lists
only the code points whose piece differs from the code point itself. (Known approximation:
UTS #39 re-applies NFD to the whole string, which may reorder combining marks across a
code-point boundary. Two NFC identifiers that differ only that way are not told apart
from each other here; no Arabic or Latin letter needs it.) Hangul syllables are not
listed: the runtime decomposes them arithmetically (UAX #15) and looks up each jamo, and
the generator checks that this gives the same piece.

Sources:

- `confusables.txt` from UTS #39 (pass its path; the file is not vendored). Source:
  https://www.unicode.org/Public/security/16.0.0/confusables.txt (sha256 95bd0aad6dced5eb
  c63436f459c06ab21a8d107cd842fb57f5c3a1e91bca8611). The generated header records its
  version line and SHA-256.
- Python `unicodedata` for NFKC, NFD and XID_Continue (`str.isidentifier`). Its Unicode
  version is recorded in the header too; skew against the confusables version only affects
  code points assigned in between, which are SEC0112 (unassigned) for the lexer anyway.
- `arabic_fold` (spec 5.3, DECISIONS D19), copied from kalam-skins `arabic_fold`. The unit
  test `arabic_fold_matches_kalam_skins` in kalam-resolve keeps the two in step.

Usage, from compiler/:
    python -I crates/kalam-resolve/tools/gen_skeleton_table.py CONFUSABLES.txt          # write
    python -I crates/kalam-resolve/tools/gen_skeleton_table.py CONFUSABLES.txt --check  # stale? exit 1
"""

import hashlib
import pathlib
import sys
import unicodedata

OUT = pathlib.Path(__file__).resolve().parent.parent / "src" / "skeleton_table.rs"

ARABIC_FOLD = {
    0x0623: 0x0627, 0x0625: 0x0627, 0x0622: 0x0627, 0x0671: 0x0627,  # أ إ آ ٱ -> ا
    0x0649: 0x064A, 0x06CC: 0x064A,                                  # ى ی -> ي
    0x06A9: 0x0643,                                                  # ک -> ك
    0x0629: 0x0647, 0x06D5: 0x0647, 0x06BE: 0x0647, 0x06C0: 0x0647,  # ة ە ھ ۀ -> ه
    0x0624: 0x0648,                                                  # ؤ -> و
    0x0626: 0x064A,                                                  # ئ -> ي
}


def arabic_fold(s):
    return "".join(chr(ARABIC_FOLD.get(ord(ch), ord(ch))) for ch in s)


def read_confusables(path):
    data = pathlib.Path(path).read_bytes()
    text = data.decode("utf-8-sig")
    version = next(
        (l[1:].strip() for l in text.splitlines() if l.startswith("# Version:")),
        "# Version: unknown",
    )
    protos = {}
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        fields = [f.strip() for f in line.split(";")]
        src = int(fields[0], 16)
        dst = "".join(chr(int(h, 16)) for h in fields[1].split())
        protos[src] = dst
    return protos, version, hashlib.sha256(data).hexdigest()


def piece(c, protos):
    s = unicodedata.normalize("NFKC", chr(c))
    s = arabic_fold(s)
    s = unicodedata.normalize("NFD", s)
    s = "".join(protos.get(ord(ch), ch) for ch in s)
    return unicodedata.normalize("NFD", s)


HANGUL_FIRST, HANGUL_LAST = 0xAC00, 0xD7A3


def is_hangul_syllable(c):
    return HANGUL_FIRST <= c <= HANGUL_LAST


def can_continue(c):
    if 0xD800 <= c <= 0xDFFF:
        return False
    return ("a" + chr(c)).isidentifier()


def rust_str(s):
    return "".join(
        ch if 0x20 <= ord(ch) < 0x7F and ch not in "\"\\" else "\\u{%X}" % ord(ch)
        for ch in s
    )


def generate(path):
    protos, version, digest = read_confusables(path)
    rows = []
    pieces = {}
    for c in range(0x110000):
        if not can_continue(c):
            continue
        p = piece(c, protos)
        pieces[c] = p
        if p != chr(c) and not is_hangul_syllable(c):
            rows.append((c, p))
    # Hangul syllables are left out (11,172 rows): the runtime decomposes them
    # arithmetically and looks each jamo up instead. Check that this gives the same piece.
    for c in range(HANGUL_FIRST, HANGUL_LAST + 1):
        jamo = unicodedata.normalize("NFD", chr(c))
        via_jamo = "".join(pieces.get(ord(j), j) for j in jamo)
        if via_jamo != pieces[c]:
            sys.exit("Hangul U+%04X: jamo pieces differ from the syllable piece" % c)
    out = [
        "// @generated by crates/kalam-resolve/tools/gen_skeleton_table.py. Do not edit.",
        "//",
        "// Identifier skeleton pieces (spec 5.3): NFD(prototypes(NFD(arabic_fold(NFKC(c))))) for",
        "// every identifier code point whose piece is not the code point itself, except Hangul",
        "// syllables (decomposed arithmetically at run time).",
        "// confusables.txt (https://www.unicode.org/Public/security/): %s, sha256 %s"
        % (version, digest),
        "// Python unicodedata (NFKC, NFD, XID_Continue): Unicode %s" % unicodedata.unidata_version,
        "",
        "/// `confusables.txt` version the table was built from.",
        'pub const CONFUSABLES_VERSION: &str = "%s";' % version.replace("Version:", "").strip(),
        "",
        "/// `(code point, skeleton piece)`, sorted by code point.",
        "pub static PIECES: &[(u32, &str)] = &[",
    ]
    for c, p in rows:
        out.append('    (0x%04X, "%s"),' % (c, rust_str(p)))
    out.append("];")
    return "\n".join(out) + "\n"


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    if len(args) != 1:
        sys.exit(__doc__)
    text = generate(args[0])
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            sys.exit("skeleton_table.rs is stale: rerun gen_skeleton_table.py")
        return
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print("wrote %s" % OUT)


if __name__ == "__main__":
    main()
